// `interval_pending` is NOT produced by intervalBlockReason: it is the guard
// on the plan/seat paths when the pending phase already changes the interval
// (a rewrite of that phase would silently drop the scheduled interval change).
type IntervalBlockReason =
    | "pending_change"
    | "cancel_scheduled"
    | "past_due"
    | "not_active"
    | "discount"
    | "interval_pending";

type IntervalChangeContext = {
    req: Request;
    action: "preview" | "commit";
    stripe: Stripe;
    admin: ReturnType<typeof createClient>;
    sub: Stripe.Subscription;
    tenant: { stripe_customer_id: string; stripe_subscription_id: string };
    tenantId: string;
    itemId: string;
    currentPlan: string;
    currentSeats: number;
    currentInterval: BillingInterval;
    targetInterval: BillingInterval;
    newPriceId: string;
    currency: string;
    trialEndsAt: string | null;
    buildKey: (params: Parameters<typeof buildIdempotencyKey>[0]) => string;
    getRecipient: () => Promise<string | null>;
    requestId: string;
    periodEndIso: string | null;
};

/** Sum of the proration (credit) lines and of the full-period lines of a preview/invoice. */
function splitInvoiceLines(invoice: Stripe.Invoice): {
    prorationCents: number;
    fullPeriodCents: number;
    fullPeriodEndSec: number | null;
} {
    let prorationCents = 0;
    let fullPeriodCents = 0;
    let fullPeriodEndSec: number | null = null;
    for (const line of invoice.lines?.data ?? []) {
        const details = (line as { parent?: { subscription_item_details?: { proration?: boolean } } }).parent
            ?.subscription_item_details;
        if (details?.proration) {
            prorationCents += line.amount ?? 0;
        } else {
            fullPeriodCents += line.amount ?? 0;
            const end = line.period?.end ?? null;
            if (end && (fullPeriodEndSec === null || end > fullPeriodEndSec)) fullPeriodEndSec = end;
        }
    }
    return { prorationCents, fullPeriodCents, fullPeriodEndSec };
}

/**
 * Why the interval change is refused right now, or null when allowed. Checked
 * in the same order the UI lists the reasons. A one-phase schedule (no real
 * pending change) does not block: it is released before the update, like the
 * upgrade path does.
 */
async function intervalBlockReason(
    stripe: Stripe,
    sub: Stripe.Subscription
): Promise<{ reason: IntervalBlockReason; scheduleId: string | null } | null> {
    const scheduleId =
        typeof sub.schedule === "string" ? sub.schedule : (sub.schedule as { id?: string })?.id ?? null;
    if (scheduleId) {
        try {
            const sched = await stripe.subscriptionSchedules.retrieve(scheduleId);
            if ((sched.phases ?? []).length >= 2) return { reason: "pending_change", scheduleId };
        } catch (err) {
            const message = err instanceof Error ? err.message : String(err);
            console.error(`stripe-change-subscription: interval schedule retrieve failed: ${message}`);
            // Fail-closed: cannot prove there is no pending change.
            return { reason: "pending_change", scheduleId };
        }
    }
    if (sub.cancel_at_period_end) return { reason: "cancel_scheduled", scheduleId };
    if (sub.status === "past_due" || sub.status === "unpaid") return { reason: "past_due", scheduleId };
    if (sub.status !== "active" && sub.status !== "trialing") return { reason: "not_active", scheduleId };
    if (extractDiscount(sub)) return { reason: "discount", scheduleId };
    return null;
}

async function handleIntervalUp(ctx: IntervalChangeContext): Promise<Response> {
    const { req, stripe, sub, tenant, tenantId, itemId, newPriceId, currentSeats } = ctx;
    const isTrialing = sub.status === "trialing";

    const blocked = await intervalBlockReason(stripe, sub);
    if (blocked) {
        return json(req, 422, { error: "INTERVAL_CHANGE_BLOCKED", details: { reason: blocked.reason } });
    }

    const newItems = [{ id: itemId, price: newPriceId, quantity: currentSeats }];

    // Full recurring total of the target (yearly) Price from its tiers: the
    // figure the customer will pay at every renewal, independent of proration.
    const yearlyTotalCents = await graduatedTotalFromPrice(stripe, newPriceId, currentSeats);
    if (yearlyTotalCents == null) {
        console.error(`stripe-change-subscription: interval-up yearly total unavailable for ${newPriceId}`);
        return json(req, 502, { error: "preview_failed" });
    }

    // ----------------------------- PREVIEW -----------------------------
    if (ctx.action === "preview") {
        let preview: Stripe.Invoice;
        try {
            preview = await stripe.invoices.createPreview({
                customer: tenant.stripe_customer_id,
                subscription: tenant.stripe_subscription_id,
                subscription_details: { items: newItems, proration_behavior: "always_invoice" }
            });
        } catch (err) {
            const message = err instanceof Error ? err.message : String(err);
            console.error(`stripe-change-subscription: interval-up preview failed: ${message}`);
            return json(req, 502, { error: "preview_failed" });
        }
        const lines = splitInvoiceLines(preview);
        const chargeToday = Math.max(0, preview.amount_due ?? 0);
        // Trialing: the preview holds a single €0 trial line whose period ends
        // at trial_end — that is when the first yearly charge happens. Active:
        // the yearly line's period.end is the new renewal date (today + 1 year).
        const nextDateSec = isTrialing ? (sub.trial_end ?? null) : lines.fullPeriodEndSec;
        return json(req, 200, {
            classification: "interval-up",
            plan: ctx.currentPlan,
            seats: currentSeats,
            currency: ctx.currency,
            chargeToday,
            nextAmount: yearlyTotalCents,
            nextDate: toIso(nextDateSec),
            effective: "now",
            trialEndsAt: ctx.trialEndsAt,
            trialFirstInvoiceCents: isTrialing ? yearlyTotalCents : null,
            // Credit for the unused part of the current month (negative cents;
            // 0 while trialing, nothing has been paid yet).
            prorationCreditCents: isTrialing ? 0 : lines.prorationCents,
            currentInterval: ctx.currentInterval,
            targetInterval: ctx.targetInterval,
            willDiscardScheduledChange: false
        });
    }

    // ----------------------------- COMMIT ------------------------------
    // Only a one-phase schedule can be attached here (a real pending change
    // was refused above): release it, Stripe rejects updates on a
    // schedule-managed subscription.
    const scheduleId =
        typeof sub.schedule === "string" ? sub.schedule : (sub.schedule as { id?: string })?.id ?? null;
    await releaseScheduleIfAny(stripe, scheduleId);

    const intervalKey = ctx.buildKey({
        operation: "interval-up",
        tenantId,
        subscriptionId: tenant.stripe_subscription_id,
        currentPlan: ctx.currentPlan,
        currentSeats,
        targetPlan: ctx.currentPlan,
        targetSeats: currentSeats,
        currentInterval: ctx.currentInterval,
        targetInterval: ctx.targetInterval
    });

    let updated: Stripe.Subscription;
    try {
        updated = await stripe.subscriptions.update(
            tenant.stripe_subscription_id,
            {
                items: newItems,
                proration_behavior: "always_invoice",
                payment_behavior: "error_if_incomplete",
                expand: ["latest_invoice"],
                metadata: { ...(sub.metadata ?? {}), plan_code: ctx.currentPlan }
            },
            { idempotencyKey: intervalKey }
        );
    } catch (err) {
        const message = err instanceof Error ? err.message : String(err);
        const type = (err as { type?: string })?.type ?? "";
        const code = (err as { code?: string })?.code ?? "";
        if (
            type === "StripeCardError" ||
            code === "subscription_payment_intent_requires_action" ||
            /incomplete|requires_action|card_declined|payment/i.test(message)
        ) {
            console.warn(`stripe-change-subscription: interval-up payment failed: ${message}`);
            return json(req, 402, { error: "PAYMENT_FAILED" });
        }
        console.error(`stripe-change-subscription: interval-up update failed: ${message}`);
        return json(req, 502, { error: "stripe_update_failed" });
    }

    // Renewal date from the UPDATED subscription (new cycle anchored today), or
    // trial_end while trialing — never the pre-change period end.
    const newPeriodEndSec = isTrialing ? (updated.trial_end ?? null) : periodEndSeconds(updated);
    const newPeriodEndIso = toIso(newPeriodEndSec);

    console.log(
        `stripe-change-subscription: INTERVAL_UP applied tenant=${tenantId} plan=${ctx.currentPlan} seats=${currentSeats} ${ctx.currentInterval}→${ctx.targetInterval} renewal=${newPeriodEndIso}`
    );

    // Email best-effort: amounts from the real invoice Stripe just created.
    let amountPaidTodayCents: number | null = null;
    let prorationCreditCents = 0;
    const inv = updated.latest_invoice;
    if (inv && typeof inv !== "string") {
        amountPaidTodayCents = inv.amount_paid ?? null;
        prorationCreditCents = splitInvoiceLines(inv).prorationCents;
    }
    try {
        const to = await ctx.getRecipient();
        if (to) {
            await sendEmail({
                to,
                ...intervalUpgradeEmail({
                    plan: ctx.currentPlan,
                    seats: currentSeats,
                    amountPaidTodayCents,
                    prorationCreditCents,
                    yearlyTotalCents,
                    renewalDateIso: newPeriodEndIso,
                    isTrialing
                })
            });
        }
    } catch (err) {
        console.error("[stripe-change-subscription] interval-up email error:", err);
    }

    return json(req, 200, {
        ok: true,
        classification: "interval-up",
        plan: ctx.currentPlan,
        seats: currentSeats,
        effective: "now",
        interval: ctx.targetInterval,
        currentPeriodEnd: newPeriodEndIso
    });
}

/**
 * Billing interval of the LAST phase of the subscription's schedule, or null
 * when there is no pending change (no schedule / one phase) or it cannot be
 * resolved. Shared by the state payload and by the plan/seat guard.
 */
async function pendingPhaseInterval(
    stripe: Stripe,
    admin: ReturnType<typeof createClient>,
    sub: Stripe.Subscription
): Promise<BillingInterval | null> {
    const scheduleId =
        typeof sub.schedule === "string" ? sub.schedule : (sub.schedule as { id?: string })?.id ?? null;
    if (!scheduleId) return null;
    try {
        const sched = await stripe.subscriptionSchedules.retrieve(scheduleId);
        const phases = sched.phases ?? [];
        if (phases.length < 2) return null;
        const pItem = phases[phases.length - 1].items?.[0];
        const pPriceId = typeof pItem?.price === "string" ? pItem.price : pItem?.price?.id;
        return (await lookupPlanPriceByStripeId(admin, pPriceId))?.billingInterval ?? null;
    } catch (err) {
        const message = err instanceof Error ? err.message : String(err);
        console.warn(`stripe-change-subscription: pending phase interval lookup failed: ${message}`);
        return null;
    }
}

