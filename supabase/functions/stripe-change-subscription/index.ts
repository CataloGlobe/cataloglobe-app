//   - la data di rinnovo NON e' il fine periodo corrente: Stripe azzera il
//     billing_cycle_anchor al cambio di intervallo, quindi il nuovo periodo
//     parte oggi. In preview la si legge dalla riga non prorata
//     (`lines[].period.end`), al commit dalla subscription aggiornata;
//   - in prova e' uno swap di Price a €0: nessun addebito, il primo annuale
//     parte a fine prova (trial_end preservato, verificato in sandbox).
